begin;
\ir _helpers.psql

select plan(20);
select tests.two_orgs();
select tests.create_property('Org A', 'Piso A1');
select tests.create_property('Org B', 'Piso B1');

-- Visitors without a session hold no grant at all.
select tests.authenticate_as_anon();
select throws_ok(
  $$select * from public.properties$$,
  '42501', null,
  'anon cannot read properties'
);

-- Isolation: each member sees only the properties of their organization.
select tests.authenticate_as('ana@example.org');
select results_eq(
  $$select name from public.properties$$,
  array['Piso A1'],
  'ana (Org A) sees only the properties of Org A'
);

select tests.authenticate_as('carla@example.org');
select results_eq(
  $$select name from public.properties$$,
  array['Piso B1'],
  'carla (Org B) sees only the properties of Org B'
);

select tests.authenticate_as('frank@example.org');
select is_empty(
  $$select * from public.properties$$,
  'a user without organizations sees no properties'
);

-- Every member creates and edits.
select tests.authenticate_as('bruno@example.org');
select results_eq(
  $$insert into public.properties (org_id, name, address, city, region)
    values (tests.org_id('Org A'), 'Piso A2', 'Calle Inventada 2', 'Pamplona', 'ES-NC')
    returning name$$,
  array['Piso A2'],
  'staff creates a property in their organization'
);

select throws_ok(
  $$insert into public.properties (org_id, name, address, city, region)
    values (tests.org_id('Org B'), 'Intruso', 'Calle Inventada 3', 'Madrid', 'ES-MD')$$,
  '42501', null,
  'nobody creates a property in another organization'
);

select results_eq(
  $$update public.properties set city = 'Barcelona', region = 'ES-CT'
    where name = 'Piso A1' returning city$$,
  array['Barcelona'],
  'staff edits a property'
);

-- Writes on another organization's properties are filtered out.
select tests.authenticate_as('carla@example.org');
select is_empty(
  $$update public.properties set name = 'Hacked' where name = 'Piso A1' returning id$$,
  'carla cannot edit a property of Org A'
);
select is_empty(
  $$delete from public.properties where name = 'Piso A1' returning id$$,
  'carla cannot delete a property of Org A'
);

-- Only owners and admins delete.
select tests.authenticate_as('bruno@example.org');
select is_empty(
  $$delete from public.properties where name = 'Piso A2' returning id$$,
  'staff cannot delete a property'
);

select tests.as_admin();
select results_eq(
  $$select name from public.properties where org_id = tests.org_id('Org A') order by name$$,
  array['Piso A1', 'Piso A2'],
  'the denied writes left the properties of Org A intact'
);

select tests.authenticate_as('diego@example.org');
select results_eq(
  $$delete from public.properties where name = 'Piso A2' returning name$$,
  array['Piso A2'],
  'an admin deletes a property'
);

-- Only the editable columns are writable.
select tests.authenticate_as('ana@example.org');
select throws_ok(
  $$update public.properties set org_id = tests.org_id('Org B')$$,
  '42501', null,
  'a property never moves to another organization'
);
select throws_ok(
  $$insert into public.properties (id, org_id, name, address, city, region)
    values (gen_random_uuid(), tests.org_id('Org A'), 'Con id', 'Calle 4', 'Madrid', 'ES-MD')$$,
  '42501', null,
  'ids are generated by the database'
);

-- Constraints.
select throws_ok(
  $$insert into public.properties (org_id, name, address, city, region)
    values (tests.org_id('Org A'), '  ', 'Calle 5', 'Madrid', 'ES-MD')$$,
  '23514', null,
  'a blank name is rejected'
);
select throws_ok(
  $$insert into public.properties (org_id, name, address, city, region)
    values (tests.org_id('Org A'), 'Piso A1', 'Calle 6', 'Madrid', 'ES-MD')$$,
  '23505', null,
  'property names are unique within an organization'
);
select throws_ok(
  $$update public.properties set total_rent_reference_cents = -1 where name = 'Piso A1'$$,
  '23514', null,
  'a negative reference rent is rejected'
);

select tests.authenticate_as('carla@example.org');
select results_eq(
  $$insert into public.properties (org_id, name, address, city, region)
    values (tests.org_id('Org B'), 'Piso A1', 'Calle 7', 'Sevilla', 'ES-AN')
    returning name$$,
  array['Piso A1'],
  'another organization can use the same name'
);

-- The trigger overrides whatever value an update writes.
select tests.as_admin();
update public.properties set updated_at = '2000-01-01'
where org_id = tests.org_id('Org A') and name = 'Piso A1';
select results_eq(
  $$select updated_at = now() from public.properties
    where org_id = tests.org_id('Org A') and name = 'Piso A1'$$,
  array[true],
  'updated_at is set by the database on every update'
);

-- Abuse guard: 100 properties per organization.
insert into public.properties (org_id, name, address, city, region)
select tests.org_id('Org A'), 'Relleno ' || n, 'Calle 8', 'Madrid', 'ES-MD'
from generate_series(1, 99) n;

select tests.authenticate_as('ana@example.org');
select throws_ok(
  $$insert into public.properties (org_id, name, address, city, region)
    values (tests.org_id('Org A'), 'Uno de más', 'Calle 9', 'Madrid', 'ES-MD')$$,
  'P0001', 'property_limit',
  'an organization cannot have more than 100 properties'
);

select * from finish();
rollback;
